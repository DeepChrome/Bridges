"""Ship the harvested photographs with the native app.

Reads data/raw/images/ (tools/harvest_images.py) and writes:

  native/assets/img/<n>.jpg     the thumbnails, numbered — a Cyrillic file name
                                is a bundler's problem, and the number is only
                                looked up through the map below
  native/src/images.js          IMAGES: bare word -> require(...), generated, so
                                Metro sees every asset statically; and CREDITS,
                                title, author, licence and page per word, for
                                the word's entry — the credit a CC BY licence
                                asks for

Only words the curriculum carries are shipped (the payload decides); a photo
whose word has left the units is dropped from the app, not from the cache.
Only the second harvest's records ship (manifest entries with v == 2): the
first harvest's plain Commons searches were half wrong subjects, and its
public-domain pool looked a century old.

    python tools/build_images.py
"""

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw" / "images"
OUT = ROOT / "native" / "assets" / "img"
JS = ROOT / "native" / "src" / "images.js"
VERSION = 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--payload", type=Path, default=ROOT / "native" / "assets" / "data.json")
    args = ap.parse_args()

    manifest = json.loads((RAW / "manifest.json").read_text(encoding="utf-8"))
    payload = json.loads(args.payload.read_text(encoding="utf-8"))
    taught = {payload["lemmas"][i]["b"] for u in payload["units"] for i in u["w"]}

    # A word blanked in the curated terms ships no picture, whether or not the
    # harvester has been re-run since. Only harvest_images.py read this file
    # before, so blanking a wrong picture did nothing until the next harvest —
    # and the wrong picture kept shipping in the meantime.
    terms_path = ROOT / "data" / "curated" / "image_terms.json"
    blanked = set()
    if terms_path.exists():
        terms = json.loads(terms_path.read_text(encoding="utf-8"))
        blanked = {k for k, v in terms.items() if not k.startswith("_") and v == ""}

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.jpg"):
        old.unlink()
    entries, credits, total, stale = [], {}, 0, 0
    by_via = {}
    # A photograph may serve one word. Nineteen files were shipped for two or
    # three words each, and the harmful ones are those where the two words are
    # not the same thing: one picture stood for both «кот» and «кошка», both
    # «актёр» and «актриса», both «здание» and «храм». On a vocabulary card the
    # picture IS the meaning, so a shared one teaches that the two words mean
    # the same. The first word to claim a file keeps it; the rest go without,
    # which is the honest outcome (2026-09-10, the content and data reviews).
    claimed = {}
    shared = 0
    for n, (bare, info) in enumerate(sorted(manifest.items())):
        src = RAW / f"{bare}.jpg"
        if not info or bare.startswith("_") or not src.exists() or bare not in taught:
            continue
        if bare in blanked:
            continue
        if info.get("v") != VERSION:
            stale += 1
            continue
        digest = hashlib.sha1(src.read_bytes()).hexdigest()
        if digest in claimed:
            shared += 1
            continue
        claimed[digest] = bare
        name = f"{n:04d}.jpg"
        shutil.copyfile(src, OUT / name)
        total += src.stat().st_size
        entries.append((bare, name))
        by_via[info.get("via")] = by_via.get(info.get("via"), 0) + 1
        # The Russian route stores the title as "File:Файл:…" — Commons' own
        # prefix in front of the ru-wiki one — so stripping "File:" alone left
        # "Файл:" on 153 of the 346 credits.
        title = info["title"]
        for prefix in ("File:", "Файл:"):
            while title.startswith(prefix):
                title = title[len(prefix):]
        credits[bare] = {"t": title, "a": info.get("author") or "",
                         "l": info["licence"], "u": info.get("url") or ""}

    lines = ["/* Generated by tools/build_images.py — do not edit. Photographs from",
             "   Wikipedia's articles and Wikimedia Commons, free to reuse with credit",
             "   (CC0, public domain, CC BY, CC BY-SA), for the words the units teach,",
             "   keyed on the bare word. CREDITS carries each file's title, author,",
             "   licence and page, shown on the word's entry. */",
             "", "export const IMAGES = {"]
    for bare, name in entries:
        lines.append(f'  "{bare}": require("../assets/img/{name}"),')
    lines.append("};")
    lines.append("")
    # The file each word ships, by name. A bundler turns every require() into the
    # same opaque handle under test, so "one photograph, one word" cannot be
    # checked through IMAGES — and it is worth checking: nineteen files were
    # shipped for two or three words each.
    lines.append("export const FILES = "
                 + json.dumps({b: n for b, n in entries}, ensure_ascii=False, indent=1) + ";")
    lines.append("")
    lines.append("export const CREDITS = " + json.dumps(credits, ensure_ascii=False, indent=1) + ";")
    lines.append("")
    JS.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {JS}")
    print(f"  photos shipped : {len(entries)} of {len(taught)} words taught "
          f"({', '.join(f'{k} {v}' for k, v in sorted(by_via.items()))}; {stale} first-harvest records left out)")
    print(f"  bytes          : {total / 1_048_576:.1f} MB")
    print(f"  shared files   : {shared} word(s) left without a picture rather than "
          f"share one already used")
    print(f"  blanked by eye : {len(blanked)} word(s) in image_terms.json")


if __name__ == "__main__":
    main()
